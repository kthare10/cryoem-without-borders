#!/usr/bin/env python3
"""CryoEM Without Borders - live demo web app (runs ON the GPU node, 127.0.0.1 only).

Reach it with a LoomAI tunnel to node "cryoem", port 8080 (or an SSH tunnel).

It drives and watches the same pipeline as notebook §7b:
  * Start: copies the run kit the notebook prepared (§7c: run.sh / ship.sh / ctf_one.sh
    generated by §7b, plus the movie list) into a fresh ~/cryoem-work/live-<time>/ with
    the first N movies, and starts run.sh detached. MotionCor3 + CTFFIND4 run per batch,
    and ship.sh streams each batch to the receiver (FIU) and verifies it there.
  * Watch: reads the run's own files (done.txt, mc_batches.txt, segments.txt,
    ship_log.txt, ...), nvidia-smi, and the transfer NIC's byte counters.
  * Shows the newest aligned micrograph and its CTFFIND4 fit as they appear, and the
    demo batch's before/after figures (notebook §7).

Config: ~/cryoem-work/app/app.json (written by notebook §7c). Without it the page
says what to run first.
"""

from __future__ import annotations

import argparse
import fcntl
import glob
import json
import mimetypes
import os
import re
import signal
import subprocess
import threading
import time

from flask import Flask, Response, jsonify, request

HERE = os.path.dirname(os.path.abspath(__file__))
HOME = os.path.expanduser("~")
WORK = os.path.join(HOME, "cryoem-work")
APP_DIR = os.path.join(WORK, "app")
CONF = os.path.join(APP_DIR, "app.json")
KIT = os.path.join(APP_DIR, "kit")
CACHE = os.path.join(APP_DIR, "cache")
LIVE_PREFIX = "live-"
CTF_NO_FIT = 100.0          # CTFFIND reports ~717 Å when it finds no fit; treat > this as "no fit"

app = Flask(__name__, static_folder=None)
_lock = threading.Lock()
_start_lock = threading.Lock()
_children = []          # runs this app started: polled so finished ones are reaped, not zombies
_children_lock = threading.Lock()
_link = {"t": None, "tx": None, "rx": None, "gbps": 0.0, "iface": None}
_latest = {"stem": None, "info": None, "t": 0}


# --- helpers ----------------------------------------------------------------------
def sh(cmd: str, timeout: int = 20) -> str:
    try:
        return subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout).stdout
    except subprocess.TimeoutExpired:
        return ""


def err(msg: str, code: int = 400):
    return jsonify({"error": msg}), code


def conf() -> dict | None:
    try:
        with open(CONF) as fh:
            return json.load(fh)
    except Exception:
        return None


def read(path: str, default: str = "") -> str:
    try:
        with open(path) as fh:
            return fh.read()
    except Exception:
        return default


def fnum(path: str) -> float:
    try:
        return float(read(path).split()[0])
    except Exception:
        return 0.0


def alive(pidfile: str) -> bool:
    try:
        os.kill(int(read(pidfile).split()[0]), 0)
        return True
    except Exception:
        return False


def runs() -> list:
    """Live runs started by this app, newest first."""
    return sorted(glob.glob(os.path.join(WORK, LIVE_PREFIX + "*")), reverse=True)


def busy() -> str | None:
    """A run (from the app or the notebook) still processing on this node, or None."""
    with _children_lock:                             # reap our own finished runs first
        _children[:] = [p for p in _children if p.poll() is None]
    for d in glob.glob(os.path.join(WORK, "*")):
        if alive(os.path.join(d, "run.pid")) and not os.path.exists(os.path.join(d, "DONE")) \
                and not os.path.exists(os.path.join(d, "FAILED")):
            return os.path.basename(d)
    return None


# --- run status (same bookkeeping as notebook §7b) ----------------------------------
def run_status(d: str, c: dict) -> dict:
    n_total = len([l for l in read(os.path.join(d, "movies.txt")).splitlines() if l.strip()])
    done = {l.strip() for l in read(os.path.join(d, "done.txt")).splitlines() if l.strip()}
    batches = [l.split() for l in read(os.path.join(d, "mc_batches.txt")).splitlines() if len(l.split()) >= 4]
    n_timed = sum(int(b[0]) for b in batches)
    in_bytes = sum(float(b[1]) for b in batches)
    mc_s = sum(float(b[2]) for b in batches)
    ctf_s = sum(float(b[3]) for b in batches)
    if os.path.exists(os.path.join(d, "DONE")):
        state = "DONE"
    elif os.path.exists(os.path.join(d, "FAILED")):
        state = "FAILED"
    elif alive(os.path.join(d, "run.pid")):
        state = "RUNNING"
    else:
        state = "STOPPED"
    closed = sum(float(b) - float(a) for a, b in
                 (l.split() for l in read(os.path.join(d, "segments.txt")).splitlines() if len(l.split()) == 2))
    seg0 = fnum(os.path.join(d, "seg_start"))
    wall_s = closed + (time.time() - seg0 if state == "RUNNING" and seg0 else 0)

    fits = []
    for f in glob.glob(os.path.join(d, "mics", "ctf", "*_ctf.txt")):
        last = read(f).strip().splitlines()[-1:] or [""]
        p = last[0].split()
        if len(p) >= 7:
            try:
                fits.append(float(p[6]))
            except ValueError:
                pass
    good = sorted(x for x in fits if x < CTF_NO_FIT)

    ship = [l.split() for l in read(os.path.join(d, "ship_log.txt")).splitlines() if len(l.split()) >= 7]
    ship_bytes = sum(float(s[2]) for s in ship)
    ship_send = sum(float(s[4]) for s in ship)
    queued = len(glob.glob(os.path.join(d, "ship", "q", "*.txt")))

    st = {"run": os.path.basename(d), "state": state, "n_total": n_total, "n_done": len(done),
          "n_ctf": len(fits), "n_timed": n_timed, "in_bytes": in_bytes, "mc_s": mc_s, "ctf_s": ctf_s,
          "wall_s": wall_s, "movies_per_min": 60 * n_timed / mc_s if mc_s else 0,
          "ctf_median_A": good[len(good) // 2] if good else None,
          "ctf_le5": sum(1 for x in good if x <= 5.0), "ctf_nofit": len(fits) - len(good),
          "ship_queued": queued, "ship_done": len(ship), "ship_bytes": ship_bytes,
          "ship_gbps": ship_bytes * 8 / ship_send / 1e9 if ship_send else None,
          "shipper": "up" if alive(os.path.join(d, "ship.pid")) else "down",
          "t_start": fnum(os.path.join(d, "t_mc_start")), "t_done": fnum(os.path.join(d, "t_done")),
          "t_ship_end": fnum(os.path.join(d, "t_ship_end")),
          "failed": read(os.path.join(d, "FAILED")).strip() or None,
          "ship_error": (read(os.path.join(d, "ship_errors.log")).strip().splitlines() or [""])[-1][-300:]}

    # Benchmark: the whole dataset at this run's pace vs. the workstation (as in notebook §7b).
    ws = (c or {}).get("workstation") or {}
    n_all = (c or {}).get("n_all") or n_total
    if st["n_done"] and wall_s:
        per = wall_s / st["n_done"]
        st["projected_s"] = per * n_all
        st["ws_s"] = ws.get("hours", 0) * 3600 or None
        st["speedup"] = st["ws_s"] / st["projected_s"] if st["ws_s"] else None
        st["n_all"] = n_all
    if st["t_ship_end"] and st["t_start"]:
        st["delivered_s"] = st["t_ship_end"] - st["t_start"]
    return st


# --- GPUs and the transfer link ---------------------------------------------------------
def gpus() -> list:
    out = sh("nvidia-smi --query-gpu=index,name,utilization.gpu,memory.used,memory.total,temperature.gpu "
             "--format=csv,noheader,nounits")
    rows = []
    for l in out.strip().splitlines():
        p = [x.strip() for x in l.split(",")]
        if len(p) >= 6:
            rows.append({"index": p[0], "name": p[1].replace("NVIDIA ", ""), "util": int(p[2] or 0),
                         "mem_used": int(p[3] or 0), "mem_total": int(p[4] or 0), "temp": int(p[5] or 0)})
    return rows


def xfer_iface(c: dict) -> str | None:
    """The NIC on the XFER link: the one holding the address the ssh alias binds to."""
    if _link["iface"]:
        return _link["iface"]
    alias = (c or {}).get("dest_ssh", "receiver")
    bind = re.search(r"^bindaddress\s+(\S+)", sh(f"ssh -G {alias}"), re.M)
    if bind:
        out = sh(f"ip -o -4 addr show | awk '$4 ~ \"^{bind[1]}/\" {{print $2}}'").strip()
        _link["iface"] = out.splitlines()[0] if out else None
    return _link["iface"]


def link_rate(c: dict) -> dict:
    """Gb/s on the transfer NIC since the previous poll (both directions)."""
    iface = xfer_iface(c)
    if not iface:
        return {"iface": None, "gbps": 0.0}
    tx = fnum(f"/sys/class/net/{iface}/statistics/tx_bytes")
    rx = fnum(f"/sys/class/net/{iface}/statistics/rx_bytes")
    now = time.time()
    with _lock:
        if _link["t"] and now - _link["t"] >= 0.5:
            _link["gbps"] = max(0.0, (tx - _link["tx"]) * 8 / (now - _link["t"]) / 1e9)
        if not _link["t"] or now - _link["t"] >= 0.5:
            _link.update(t=now, tx=tx, rx=rx)
        return {"iface": iface, "gbps": round(_link["gbps"], 3), "tx_bytes": tx}


# --- newest micrograph, rendered as it appears ------------------------------------------------
def _png(img, path: str, size: int = 640) -> None:
    import numpy as np
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.image as mpimg

    a = np.asarray(img, dtype=np.float32)
    f = max(1, max(a.shape) // size)
    h, w = (a.shape[0] // f) * f, (a.shape[1] // f) * f
    a = a[:h, :w].reshape(h // f, f, w // f, f).mean(axis=(1, 3))
    lo, hi = np.percentile(a, (1, 99))
    a = np.clip((a - lo) / (hi - lo or 1), 0, 1)
    tmp = path + ".tmp.png"
    mpimg.imsave(tmp, a, cmap="gray")
    os.replace(tmp, path)


def render_latest() -> None:
    """Background loop: when a new CTF fit appears in the newest run, render its aligned
    micrograph (the _DW sum, kept until the batch is verified at the receiver) and the
    CTFFIND4 diagnostic. Renders before the shipper deletes them."""
    import mrcfile

    os.makedirs(CACHE, exist_ok=True)
    while True:
        try:
            for d in runs()[:1]:
                fits = sorted(glob.glob(os.path.join(d, "mics", "ctf", "*_ctf.txt")), key=os.path.getmtime)
                for f in reversed(fits[-5:]):
                    stem = os.path.basename(f)[:-len("_ctf.txt")]
                    key = f"{os.path.basename(d)}__{stem}"
                    if _latest["stem"] == key:
                        break
                    mic = next((m for m in (os.path.join(d, "mics", f"{stem}_DW.mrc"),
                                            os.path.join(d, "mics", f"{stem}.mrc")) if os.path.exists(m)), None)
                    diag = os.path.join(d, "mics", "ctf", f"{stem}_ctf.mrc")
                    if not mic or not os.path.exists(diag):
                        continue
                    with mrcfile.open(mic, permissive=True) as m:
                        _png(m.data, os.path.join(CACHE, "latest_mic.png"), 768)
                    with mrcfile.open(diag, permissive=True) as m:
                        data = m.data[0] if m.data.ndim == 3 else m.data
                        _png(data, os.path.join(CACHE, "latest_ctf.png"), 512)
                    p = read(f).strip().splitlines()[-1].split()
                    _latest.update(stem=key, t=time.time(), info={
                        "micrograph": stem, "run": os.path.basename(d),
                        "defocus_um": round((float(p[1]) + float(p[2])) / 2 / 1e4, 2),
                        "astig_A": round(abs(float(p[1]) - float(p[2]))),
                        "fit_A": round(float(p[6]), 2)})
                    break
        except Exception as exc:                      # never let the renderer die
            _latest["error"] = str(exc)[:200]
        time.sleep(3)


# --- API -----------------------------------------------------------------------------------
@app.get("/api/info")
def info():
    c = conf()
    kit_ok = all(os.path.exists(os.path.join(KIT, f)) for f in ("run.sh", "ship.sh", "ctf_one.sh", "all_movies.txt"))
    return jsonify({"configured": bool(c), "kit": kit_ok, "conf": c or {}, "gpus": gpus(),
                    "hint": None if c and kit_ok else
                    "Run the notebook through §7b once, then §7c: it prepares this app (config + run kit)."})


@app.get("/api/poll")
def poll():
    c = conf() or {}
    b = busy()                                       # first: it reaps finished runs
    rs = runs()
    st = run_status(rs[0], c) if rs else None
    return jsonify({"t": time.time(), "run": st, "busy": b, "gpus": gpus(), "link": link_rate(c),
                    "latest": _latest.get("info"), "latest_t": _latest.get("t"),
                    "past": [os.path.basename(r) for r in rs[1:6]]})


@app.post("/api/run/start")
def start_run():
    c = conf()
    if not c:
        return err("Not prepared yet: run notebook §7c first.")
    try:
        n = int((request.json or {}).get("movies", 50))
    except (TypeError, ValueError):
        return err("movies must be a number")
    movies = [l for l in read(os.path.join(KIT, "all_movies.txt")).splitlines() if l.strip()]
    if not movies:
        return err("The run kit has no movie list: re-run notebook §7c.")
    n = max(1, min(n, len(movies)))
    # Check-and-launch is one critical section (threads of this app, and any other process
    # using the same lock file), and run.pid is written as soon as the process exists, so two
    # Start clicks can never both pass busy() and put two runs on the GPUs.
    os.makedirs(APP_DIR, exist_ok=True)
    with _start_lock, open(os.path.join(APP_DIR, "start.lock"), "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        b = busy()
        if b:
            return err(f"A run is already processing on this node ({b}). Stop it first.")
        return _launch(c, movies[:n])


def _launch(c: dict, movies: list):
    n = len(movies)
    name = LIVE_PREFIX + time.strftime("%Y%m%d-%H%M%S")
    d = os.path.join(WORK, name)
    if os.path.exists(d):
        return err("A run was started this second; try again.", 409)
    os.makedirs(os.path.join(d, "mics", "logs"))
    os.makedirs(os.path.join(d, "mics", "ctf"))
    os.makedirs(os.path.join(d, "movies"))
    kit_work, kit_ship = c["kit"]["work"], c["kit"]["ship_dir"]
    new_work = kit_work.rsplit("/", 1)[0] + "/" + name
    new_ship = kit_ship.rsplit("/", 1)[0] + "/" + name
    for f in ("run.sh", "ship.sh", "ctf_one.sh"):
        text = read(os.path.join(KIT, f)).replace(kit_work, new_work).replace(kit_ship, new_ship)
        with open(os.path.join(d, f), "w") as fh:
            fh.write(text)
        os.chmod(os.path.join(d, f), 0o755)
    with open(os.path.join(d, "movies.txt"), "w") as fh:
        fh.write("\n".join(movies) + "\n")
    with open(os.path.join(d, "app_run.json"), "w") as fh:
        json.dump({"movies": n, "started": time.time(), "ship_dir": new_ship}, fh)
    alias = c.get("dest_ssh", "receiver")
    sh(f"ssh -o BatchMode=yes -o ConnectTimeout=10 {alias} 'mkdir -p {new_ship}'", timeout=20)
    with open(os.path.join(d, "run.out"), "w") as out:      # detached: survives app restarts
        p = subprocess.Popen(["nohup", "./run.sh"], cwd=d, stdout=out, stderr=subprocess.STDOUT,
                             stdin=subprocess.DEVNULL, start_new_session=True)
    with _children_lock:
        _children.append(p)
    # nohup execs run.sh, so this is run.sh's own pid (it writes the same value itself).
    with open(os.path.join(d, "run.pid"), "w") as fh:
        fh.write(f"{p.pid}\n")
    return jsonify({"run": name, "movies": n})


@app.post("/api/run/stop")
def stop_run():
    rs = runs()
    if not rs:
        return err("No run to stop.")
    d = rs[0]
    for p in ("run.pid", "ship.pid"):
        try:
            os.kill(int(read(os.path.join(d, p)).split()[0]), signal.SIGTERM)
        except Exception:
            pass
    sh(f"pkill -f '[c]ryoem-work/{os.path.basename(d)}/'")
    return jsonify({"stopped": os.path.basename(d)})


@app.get("/api/latest/<which>.png")
def latest_png(which):
    if which not in ("mic", "ctf"):
        return err("not found", 404)
    return _file(os.path.join(CACHE, f"latest_{which}.png"), "image/png", 0)


@app.get("/api/gallery")
def gallery():
    """The demo batch's before/after figures (notebook §7)."""
    c = conf() or {}
    try:
        summ = json.load(open(os.path.expanduser(c.get("demo_summary", ""))))
    except Exception:
        return jsonify([])
    out = []
    for i, s in enumerate(summ):
        ctf = s.get("ctf") or {}
        out.append({"i": i, "micrograph": s.get("micrograph"), "zoom": bool(s.get("zoom_figure")),
                    "drift_px": s.get("total_drift_px"), "fit_A": ctf.get("fit_resolution_A"),
                    "hf_gain": s.get("hf_gain")})
    return jsonify(out)


@app.get("/api/gallery/<int:i>/<kind>.png")
def gallery_png(i, kind):
    c = conf() or {}
    try:
        s = json.load(open(os.path.expanduser(c.get("demo_summary", ""))))[i]
    except Exception:
        return err("not found", 404)
    path = s.get("zoom_figure") if kind == "zoom" else s.get("figure")
    if not path or not path.startswith(WORK + "/"):
        return err("not found", 404)
    return _file(path, "image/png", 3600)


# --- page and static files (whole bodies: proxies such as LoomAI's tunnel relay them reliably) --
def _file(path: str, mime: str, max_age: int) -> Response:
    try:
        with open(path, "rb") as fh:
            body = fh.read()
    except OSError:
        return err("not found", 404)
    r = Response(body, mimetype=mime)
    r.headers["Cache-Control"] = f"public, max-age={max_age}" if max_age else "no-cache"
    return r


@app.get("/")
def index():
    return _file(os.path.join(HERE, "index.html"), "text/html", 0)


@app.get("/static/<path:name>")
def static_file(name):
    base = os.path.realpath(os.path.join(HERE, "static"))
    path = os.path.realpath(os.path.join(base, name))
    if not path.startswith(base + os.sep):
        return err("not found", 404)
    return _file(path, mimetypes.guess_type(path)[0] or "application/octet-stream", 3600)


